// Event priorities — higher wins; ambient events sit at 1.
export const PRI: Record<string, number> = {
  medal: 5,
  trophy: 5,
  gem: 5,
  heart: 4,
  flame: 4,
  star: 4,
  cake: 4,
  confetti: 3,
  bolt: 3,
  'confetti ball': 3,
  'welcome back': 2,
  sun: 2,
  moon: 2,
  smiley: 2,
  hourglass: 2,
  bat: 2,
};

export interface GlyphEvent {
  name: GlyphName;
  until: number;
  total: number;
  ambient: boolean;
  pri: number;
}

export function mkEvent(name: GlyphName, ms: number, ambient = false): GlyphEvent {
  return {
    name,
    until: Date.now() + ms,
    total: ms,
    ambient,
    pri: ambient ? 1 : PRI[name] || 2,
  };
}

// Which bitmap frame a glyph shows at the current animation phase.
export function frameFor(name: GlyphName, phase: number, elapsed: number | null): string | null {
  if (name === 'smiley') return phase % 12 < 2 ? 'smileyBlink' : 'smiley';
  if (name === 'flame') return phase % 4 < 2 ? 'flame' : 'flame2';
  if (name === 'sun') return phase % 8 < 2 ? 'sun2' : 'sun';
  if (name === 'heart') {
    const m = phase % 10;
    return m === 0 || m === 1 || m === 3 || m === 4 ? 'heart' : 'heart2';
  }
  if (name === 'moon') return phase % 10 < 2 ? 'moon2' : 'moon';
  if (name === 'welcome back') {
    const idx = elapsed == null ? Math.floor(phase / 4) % 4 : Math.min(3, Math.floor(elapsed / 1000));
    return 'wb' + idx;
  }
  if (name === 'idle') {
    const m = phase % 70;
    return m < 40 ? 'ring' + Math.floor(m / 10) : 'blank';
  }
  if (name === 'medal') return 'medal';
  if (name === 'trophy') return 'trophy';
  if (name === 'cake') {
    const m = phase % 6;
    return m < 2 ? 'cake' : m < 4 ? 'cake2' : 'cake3';
  }
  if (name === 'star') return phase % 6 < 2 ? 'star2' : 'star';
  if (name === 'gem') return 'gem';
  if (name === 'bolt') return 'bolt';
  if (name === 'hourglass') return 'hourglass';
  if (name === 'bat') return phase % 6 < 3 ? 'bat2' : 'bat';
  if (name === 'confetti ball') return 'ball';
  return GLYPHS[name] ? name : null;
}

